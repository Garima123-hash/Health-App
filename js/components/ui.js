function icon(name) {
  return ICONS[name] || ICONS.document;
}

export function stat(title, value, iconName, foot) {
  return `<article class="stat-card">
    <div class="stat-head">
      <span>${escapeHtml(title)}</span>
      <span class="stat-icon">${icon(iconName)}</span>
    </div>
    <div class="stat-value">${escapeHtml(value)}</div>
    <div class="stat-foot">${foot}</div>
  </article>`;
}

export function panelHead(title, sub = '', action = '') {
  return `<div class="panel-head">
    <div>
      <h2>${escapeHtml(title)}</h2>
      ${sub ? `<p>${escapeHtml(sub)}</p>` : ''}
    </div>
    ${action}
  </div>`;
}

export function quick(iconName, title, desc, action) {
  return `<button class="quick-action" onclick="${action}">
    <div class="qa-dot">${icon(iconName)}</div>
    <strong>${escapeHtml(title)}</strong>
    <span>${escapeHtml(desc)}</span>
  </button>`;
}

